-- 1. BẢNG DANH MỤC QUYỀN (ROLES)
CREATE TABLE IF NOT EXISTS "AspNetRoles" (
    "Id" text NOT NULL,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text,
    CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
);

-- 2. BẢNG TÀI KHOẢN NGƯỜI DÙNG (USERS)
CREATE TABLE IF NOT EXISTS "AspNetUsers" (
    "Id" text NOT NULL,
    "FullName" text,
    "AvatarUrl" text,
    "CreatedAt" timestamp with time zone NOT NULL,
    "PasswordResetOtp" text,
    "PasswordResetOtpExpiry" timestamp with time zone,
    "LoginOtp" text,
    "LoginOtpExpiry" timestamp with time zone,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
);

-- 3. BẢNG CLAIM CỦA ROLE
CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "RoleId" text NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
);

-- 4. BẢNG CLAIM CỦA USER
CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "ClaimType" text,
    "ClaimValue" text,
    CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- 5. BẢNG LOGIN LIÊN KẾT BÊN NGOÀI
CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- 6. BẢNG GÁN ROLE CHO USER
CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
    "UserId" text NOT NULL,
    "RoleId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- 7. BẢNG TOKEN CỦA USER
CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
    "UserId" text NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- 8. BẢNG NHÓM GIA ĐÌNH (FAMILY GROUPS)
CREATE TABLE IF NOT EXISTS family_groups (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name character varying(150) NOT NULL,
    description text,
    owner_id text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_family_groups" PRIMARY KEY (id),
    CONSTRAINT "FK_family_groups_AspNetUsers_owner_id" FOREIGN KEY (owner_id) REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- 9. BẢNG THÀNH VIÊN GIA ĐÌNH (FAMILY MEMBERS)
CREATE TABLE IF NOT EXISTS family_members (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    family_group_id integer NOT NULL,
    user_id text NOT NULL,
    role_in_family character varying(50) NOT NULL DEFAULT 'Parent',
    joined_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_family_members" PRIMARY KEY (id),
    CONSTRAINT "FK_family_members_AspNetUsers_user_id" FOREIGN KEY (user_id) REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_family_members_family_groups_family_group_id" FOREIGN KEY (family_group_id) REFERENCES family_groups (id) ON DELETE CASCADE
);

-- 10. BẢNG MÃ QR MỜI VÀO GIA ĐÌNH (FAMILY QR INVITES)
CREATE TABLE IF NOT EXISTS family_qr_invites (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    family_group_id integer NOT NULL,
    created_by_user_id text NOT NULL,
    invite_token character varying(64) NOT NULL,
    short_code character varying(10) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    expires_at timestamp with time zone NOT NULL,
    is_used boolean NOT NULL,
    used_by_user_id text,
    used_at timestamp with time zone,
    CONSTRAINT "PK_family_qr_invites" PRIMARY KEY (id),
    CONSTRAINT "FK_family_qr_invites_AspNetUsers_created_by_user_id" FOREIGN KEY (created_by_user_id) REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_family_qr_invites_AspNetUsers_used_by_user_id" FOREIGN KEY (used_by_user_id) REFERENCES "AspNetUsers" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_family_qr_invites_family_groups_family_group_id" FOREIGN KEY (family_group_id) REFERENCES family_groups (id) ON DELETE CASCADE
);

-- 11. BẢNG HỒ SƠ TRẺ EM (KIDS)
CREATE TABLE IF NOT EXISTS kids (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    full_name character varying(150) NOT NULL,
    nickname character varying(50),
    date_of_birth timestamp with time zone,
    gender character varying(10),
    avatar_url text,
    school_name character varying(200),
    health_notes text,
    interests text,
    parent_id text,
    kid_user_id text,
    family_group_id integer,
    total_points integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    updated_at timestamp with time zone,
    CONSTRAINT "PK_kids" PRIMARY KEY (id),
    CONSTRAINT "FK_kids_AspNetUsers_kid_user_id" FOREIGN KEY (kid_user_id) REFERENCES "AspNetUsers" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_kids_AspNetUsers_parent_id" FOREIGN KEY (parent_id) REFERENCES "AspNetUsers" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_kids_family_groups_family_group_id" FOREIGN KEY (family_group_id) REFERENCES family_groups (id) ON DELETE SET NULL
);

-- 12. BẢNG CHẶN WEBSITE & ỨNG DỤNG (BLOCKED ITEMS)
CREATE TABLE IF NOT EXISTS blocked_items (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    kid_id integer NOT NULL,
    item_type character varying(20) NOT NULL DEFAULT 'Website',
    target character varying(255) NOT NULL,
    title character varying(150) NOT NULL,
    category character varying(50) DEFAULT 'Khác',
    reason character varying(255),
    is_blocked boolean NOT NULL DEFAULT TRUE,
    created_by_user_id text,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    updated_at timestamp with time zone,
    CONSTRAINT "PK_blocked_items" PRIMARY KEY (id),
    CONSTRAINT "FK_blocked_items_AspNetUsers_created_by_user_id" FOREIGN KEY (created_by_user_id) REFERENCES "AspNetUsers" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_blocked_items_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

-- 13. BẢNG NHẬT KÝ SINH HOẠT & NHIỆM VỤ CỦA TRẺ (KID ACTIVITIES)
CREATE TABLE IF NOT EXISTS kid_activities (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    kid_id integer NOT NULL,
    title character varying(200) NOT NULL,
    description text,
    category character varying(50) NOT NULL DEFAULT 'Sinh hoạt',
    activity_time timestamp with time zone NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'Pending',
    reward_points integer NOT NULL DEFAULT 5,
    notes text,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_kid_activities" PRIMARY KEY (id),
    CONSTRAINT "FK_kid_activities_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

-- 14. BẢNG VÙNG AN TOÀN (KID GEOFENCES)
CREATE TABLE IF NOT EXISTS kid_geofences (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    kid_id integer NOT NULL,
    name character varying(100) NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    radius_meters double precision NOT NULL DEFAULT 200.0,
    alert_on_exit boolean NOT NULL,
    alert_on_enter boolean NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_kid_geofences" PRIMARY KEY (id),
    CONSTRAINT "FK_kid_geofences_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

-- 15. BẢNG TỌA ĐỘ GPS & LỊCH SỬ DI CHUYỂN (KID LOCATIONS)
CREATE TABLE IF NOT EXISTS kid_locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    kid_id integer NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    accuracy double precision,
    speed double precision,
    altitude double precision,
    battery_level integer,
    is_charging boolean,
    address character varying(255),
    recorded_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_kid_locations" PRIMARY KEY (id),
    CONSTRAINT "FK_kid_locations_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

-- 16. BẢNG GIỚI HẠN THỜI GIAN SỬ DỤNG & KHÓA MÁY (KID SCREEN TIMES)
CREATE TABLE IF NOT EXISTS kid_screen_times (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    kid_id integer NOT NULL,
    device_name character varying(100) NOT NULL DEFAULT 'Máy tính / Điện thoại của bé',
    daily_limit_minutes integer NOT NULL DEFAULT 120,
    weekend_limit_minutes integer NOT NULL DEFAULT 180,
    is_daily_limit_enabled boolean NOT NULL,
    is_bedtime_enabled boolean NOT NULL,
    bedtime_start character varying(10) NOT NULL DEFAULT '21:30',
    bedtime_end character varying(10) NOT NULL DEFAULT '06:30',
    is_allowed_window_enabled boolean NOT NULL,
    allowed_start_time character varying(10) NOT NULL DEFAULT '07:00',
    allowed_end_time character varying(10) NOT NULL DEFAULT '21:00',
    is_locked_now boolean NOT NULL,
    lock_reason character varying(255),
    locked_at timestamp with time zone,
    bonus_minutes_today integer NOT NULL,
    bonus_date character varying(20),
    used_minutes_today integer NOT NULL,
    last_usage_date character varying(20),
    last_heartbeat_at timestamp with time zone,
    lock_message character varying(500),
    schedule_json text,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    updated_at timestamp with time zone,
    CONSTRAINT "PK_kid_screen_times" PRIMARY KEY (id),
    CONSTRAINT "FK_kid_screen_times_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

-- 17. BẢNG TIN NHẮN THOẠI & BỘ ĐÀM GIA ĐÌNH (VOICE MESSAGES)
CREATE TABLE IF NOT EXISTS voice_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    sender_id character varying(100) NOT NULL,
    sender_name character varying(100) NOT NULL,
    sender_role character varying(20) NOT NULL,
    sender_avatar_url character varying(500),
    kid_id integer NOT NULL,
    parent_id character varying(100),
    family_group_id integer,
    audio_url character varying(500) NOT NULL,
    duration_seconds integer NOT NULL,
    file_size_bytes bigint NOT NULL,
    is_heard boolean NOT NULL,
    heard_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP),
    CONSTRAINT "PK_voice_messages" PRIMARY KEY (id),
    CONSTRAINT "FK_voice_messages_kids_kid_id" FOREIGN KEY (kid_id) REFERENCES kids (id) ON DELETE CASCADE
);

